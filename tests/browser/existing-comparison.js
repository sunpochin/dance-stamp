/* 檔案用途：驗證不用相機的既有影片比較、成檔與備份重連。所在層：桌面瀏覽器回歸。主要關聯：main.js、RECORD_COMPARE.md。 */
// 筆記管理收在次要工具，先展開再驗證既有功能；資料斷言維持原樣。
async (page) => {
  const origin = new URL(page.url()).origin, checks = {};
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const idle = () => page.waitForFunction(() => !document.getElementById('controls').disabled && document.getElementById('compare').getAttribute('aria-busy') !== 'true');
  const library = () => page.evaluate(async () => (await (await import('/storage.js')).readLibrary()).data);
  const change = async (id, value) => { await page.locator(`#${id}`).fill(value); await page.locator(`#${id}`).dispatchEvent('change'); await idle(); };
  await page.addInitScript(() => {
    window.comparisonCameraRequests = 0;
    navigator.mediaDevices.getUserMedia = async () => { window.comparisonCameraRequests++; throw new Error('此驗收禁止相機／麥克風'); };
    window.confirm = () => true;
  });
  await page.goto(origin); await idle();
  await page.getByRole('button', { name: '比較已有影片', exact: true }).click();
  await page.locator('#reference-file').setInputFiles('output/media-probe/reference.mp4'); await idle();
  const videoId = await page.locator('#library').inputValue();
  await page.locator('#rate').selectOption('0.5'); await idle();
  await page.getByLabel('我的已錄影片', { exact: true }).setInputFiles('output/media-probe/reference.mp4'); await idle();
  assert(await page.locator('#rate').inputValue() === '1', '新比較繼承上次慢速');
  const initial = await library(), initialTake = initial.takes.at(-1);
  assert(initialTake?.state === 'ready', '外部選片產生假的錄影工作');
  assert(await page.evaluate(async id => !(await (await import('/storage.js')).readMedia(id)), initialTake.cameraAssetId), '選片暗中複製原片');
  await page.locator('#reference').evaluate(async video => { video.currentTime = 12; await new Promise(r => video.addEventListener('seeked', r, { once: true })); });
  await page.locator('#reference-start').click(); await idle();
  await page.locator('#self').evaluate(async video => { video.currentTime = 4; await new Promise(r => video.addEventListener('seeked', r, { once: true })); });
  await page.locator('#self-start').click(); await idle();
  await change('end', '17');
  assert(Number(await page.locator('#offset').inputValue()) === 4, '自己的起點未保存');
  const aligned = await library(), take = aligned.takes.at(-1), recipe = aligned.recipes.find(r => r.takeId === take.id);
  assert(take.referenceStartMs === 12000 && take.referenceEndMs === 17000 && recipe.offsetMs === 4000, '兩側起點映射錯誤');
  assert(aligned.takes.find(t => t.id === initialTake.id).referenceStartMs === 0, '調整區間覆寫原配方');
  const pair = await page.evaluate(() => [document.getElementById('reference').currentTime, document.getElementById('self').currentTime]);
  assert(Math.abs(pair[0] - 12) < 0.05 && Math.abs(pair[1] - 4) < 0.05, '共同定位未等待兩側 seek');
  // 不先 Tab：真實點擊的 blur 保存不能吃掉隨後的播放 click。
  await page.locator('#offset').fill('4.05'); await page.locator('#play').click();
  await page.waitForFunction(() => !document.getElementById('pause-comparison').hidden);
  await page.locator('#pause-comparison').click(); await idle();
  await change('offset', '4');
  await page.getByRole('button', { name: '＋50 毫秒', exact: true }).click(); await idle();
  await page.getByRole('button', { name: '−50 毫秒', exact: true }).click(); await idle();
  await page.locator('#play').click();
  await page.waitForFunction(() => !document.getElementById('pause-comparison').hidden);
  await page.waitForTimeout(500); await page.locator('#pause-comparison').click(); await idle();
  assert(await page.evaluate(() => document.getElementById('reference').paused && document.getElementById('self').paused), '共同暫停沒有停止兩片');
  await change('scrub', '2');
  const scrub = await page.evaluate(() => [document.getElementById('reference').currentTime, document.getElementById('self').currentTime]);
  assert(Math.abs(scrub[0] - 14) < 0.05 && Math.abs(scrub[1] - 6) < 0.05, '共同拖曳映射錯誤');
  await page.locator('#export').click(); await idle();
  assert(await page.locator('#output-download').isVisible(), '沒有產生單一 VS');
  const result = JSON.parse(await page.locator('#diagnostics').textContent()).export;
  assert(result?.decodedDurationMs > 4700 && result.decodedDurationMs < 5500, 'VS 成檔長度錯誤');
  const exporting = page.waitForEvent('download'); await page.locator('#output-download').click();
  const exported = await exporting; await exported.saveAs(`output/media-probe/existing-vs.${exported.suggestedFilename().split('.').pop()}`);
  const outputHref = await page.locator('#output-download').getAttribute('href'), beforeFailure = await library();
  await page.locator('#self-file').setInputFiles({ name: 'synthetic-broken.mp4', mimeType: 'video/mp4', buffer: Buffer.from('synthetic invalid media') }); await idle();
  assert((await library()).takes.length === beforeFailure.takes.length, '壞檔新增或取代配對');
  assert(await page.locator('#output-download').getAttribute('href') === outputHref, '壞檔破壞舊輸出');
  await change('offset', '100'); assert(await page.locator('#export').isDisabled(), '空交集允許匯出');
  await change('offset', '4');
  await page.locator('#note-tools').evaluate(d => { d.open = true; });
  const backing = page.waitForEvent('download'); await page.locator('#backup').click();
  const backup = await backing; await backup.saveAs('output/media-probe/existing-backup.json');
  await page.reload(); await idle();
  await page.locator('#library').selectOption(videoId); await page.locator('#open-library').click(); await idle();
  assert((await page.locator('#status').textContent()).includes('尚未連結'), '未選保存仍自動取回外部影片');
  await page.locator('#reference-file').setInputFiles('output/media-probe/reference.mp4'); await idle();
  await page.locator('#confirm-link').click(); await idle();
  await page.getByRole('button', { name: '開啟自拍／恢復', exact: true }).last().click(); await idle();
  await page.locator('#self-file').setInputFiles('output/media-probe/reference.mp4'); await idle();
  assert(await page.locator('#export').isDisabled(), '原片未確認便自動配對');
  await page.locator('#confirm-take').click(); await idle();
  assert(Number(await page.locator('#offset').inputValue()) === 4 && Number(await page.locator('#start').inputValue()) === 12, '重連丟失對齊設定');
  await page.locator('#copy-reference').click(); await idle(); await page.locator('#copy-self').click(); await idle();
  await page.reload(); await idle(); await page.locator('#library').selectOption(videoId); await page.locator('#open-library').click(); await idle();
  await page.getByRole('button', { name: '開啟自拍／恢復', exact: true }).last().click(); await idle();
  assert(await page.locator('#self').evaluate(v => v.videoWidth > 0) && Number(await page.locator('#offset').inputValue()) === 4, '明確保存後無法重開');
  checks.cameraRequests = await page.evaluate(() => window.comparisonCameraRequests);
  assert(checks.cameraRequests === 0, '比較流程要求相機');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '窄版水平溢出');
  return { noCameraOrMicrophone: true, separateStarts: true, versionedSegment: true, pauseAndScrub: true, output: result, invalidReplacementPreservesFiles: true, emptyIntersectionBlocked: true, sessionOnly: true, explicitRelink: true, savedCopiesReopen: true, narrowLayout: true };
}
